// Generate reviewed alias seed SQL; never connects to a database. Canonical
// varieties must already exist. Historical SQL remains immutable evidence.
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
export function normalizeAlias(alias) {
  if(typeof alias!=='string'||/[^\x00-\x7f]/.test(alias)) throw new Error('Review non-ASCII alias policy before seeding');
  const key=alias.toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
  if(!key) throw new Error('Empty alias key');
  return key;
}
export function aliasSeedRows(rows) {
  const byKey=new Map();
  for(const row of [...rows].sort((a,b)=>(a.alias===a.variety_name?-1:0)-(b.alias===b.variety_name?-1:0)||a.alias.localeCompare(b.alias,'en'))) {
    if(!/^[a-z0-9-]+$/.test(row.variety_slug)||typeof row.variety_name!=='string') throw new Error('Invalid canonical variety');
    const key=normalizeAlias(row.alias), previous=byKey.get(key);
    if(previous&&previous.variety_slug!==row.variety_slug) throw new Error('Cross-variety alias collision');
    if(!previous) byKey.set(key,{...row,key});
  }
  return [...byKey.values()].sort((a,b)=>a.key.localeCompare(b.key,'en'));
}
const literal=s=>"'"+s.replaceAll("'","''")+"'";
export function renderAliasSeed(rows) {
  const values=aliasSeedRows(rows).map(r=>`(${literal(r.variety_slug)},${literal(r.alias)},${literal(r.key)})`).join(',\n');
  return `-- Generated by scripts/reference/grape-alias-seed.mjs. Apply only to a reviewed seed target.\nbegin;\nlock table public.grape_aliases in share row exclusive mode;\ncreate temporary table reviewed_alias_seed(variety_slug text, alias text, alias_normalized text) on commit drop;\ninsert into reviewed_alias_seed values\n${values};\ndo $$ begin\n if exists(select from reviewed_alias_seed s left join public.grape_varieties v on v.slug=s.variety_slug where v.id is null) then raise exception 'Missing canonical varieties'; end if;\n if exists(select from reviewed_alias_seed s join public.grape_varieties v on v.slug=s.variety_slug join public.grape_aliases a on a.alias_normalized=s.alias_normalized where a.variety_id<>v.id) then raise exception 'Cross-variety alias collision'; end if;\nend $$;\ninsert into public.grape_aliases(variety_id,alias,alias_normalized) select v.id,s.alias,s.alias_normalized from reviewed_alias_seed s join public.grape_varieties v on v.slug=s.variety_slug on conflict(alias_normalized) do nothing;\ncommit;\n`;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href) {
  process.stdout.write(renderAliasSeed(JSON.parse(await readFile(new URL('../../supabase/reference/grape-aliases.json',import.meta.url),'utf8'))));
}
